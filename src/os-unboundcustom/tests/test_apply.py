"""Exercise DNS changes, loaded-config receipts, and failure recovery in isolation."""
import errno
import importlib.util
import json
import os
from pathlib import Path
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

PACKAGE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PACKAGE.parent / 'common'))
spec = importlib.util.spec_from_file_location('unboundcustom_apply', PACKAGE / 'src/opnsense/scripts/OPNsense/Unboundcustom/apply.py')
apply = importlib.util.module_from_spec(spec)
spec.loader.exec_module(apply)
REAL_RESOLVER = apply.resolver
REAL_PIDFILE_IDENTITY = apply.pidfile_identity


class ApplyTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='unboundcustom-transaction-')
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.fragment = self.root / 'generated.conf'
        self.runtime = self.root / 'etc/custom-options.conf'
        self.runtime.parent.mkdir()
        self.state = self.root / 'state'
        self.state.mkdir()
        (self.root / 'unbound.conf').write_text('server:\ninclude: ' + str(self.root / 'etc/*.conf') + '\n')
        self.old = b'# Generated by os-unboundcustom.\nserver:\n verbosity: 1\n'
        self.generated = b'# Generated by os-unboundcustom.\nserver:\n verbosity: 3\n'
        self.fragment.write_bytes(self.old)
        self.runtime.write_bytes(self.old)
        self.fragment.chmod(0o600)
        self.runtime.chmod(0o640)
        self.running = {'pid': 10, 'birth': '100:1234'}
        self.events = []
        self.validation_states = []
        self.failure = ''
        self.launches = 0
        self.tick = 0
        mappings = {'FRAGMENT': self.fragment, 'RUNTIME': self.runtime, 'ROOT': self.root, 'STATE': self.state}
        self.addCleanup(patch.stopall)
        patch.multiple(apply, **mappings).start()
        patch.object(apply, 'resolver', side_effect=lambda: self.running).start()
        patch.object(apply, 'process', side_effect=self.process).start()
        patch.object(apply, 'pidfile_identity', side_effect=lambda: self.process(self.running['pid']) if self.running else None).start()
        patch.object(apply.os, 'kill', side_effect=self.kill).start()
        patch.object(apply.subprocess, 'Popen', side_effect=self.launch).start()
        patch.object(apply.time, 'sleep', return_value=None).start()
        patch.object(apply.time, 'monotonic', side_effect=self.clock).start()
        patch.object(apply, 'run', side_effect=self.command).start()
        patch.object(apply.pwd, 'getpwnam', return_value=SimpleNamespace(pw_uid=os.getuid(), pw_gid=os.getgid())).start()
        # Preserve owner semantics without requiring local root for fixtures.
        self.actual_fchown = os.fchown
        patch.object(apply.os, 'fchown', side_effect=lambda fd, uid, gid: None).start()

    def command(self, command, timeout=90, cwd=None):
        self.events.append(command)
        if command[:2] == [apply.TEMPLATE_CTL, '-r']:
            target = apply.rooted(Path(command[2]), self.fragment)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(self.generated)
            target.chmod(0o600)
            if self.failure == 'template':
                raise RuntimeError('isolated template failure')
            return b'templates...done\n'
        elif command[0] == apply.CHECKCONF:
            candidate = Path(command[1]).parent / 'etc' / self.runtime.name
            if candidate.exists():
                self.validation_states.append((self.fragment.read_bytes() if self.fragment.exists() else None,
                                               self.runtime.read_bytes() if self.runtime.exists() else None,
                                               candidate.read_bytes()))
            if self.failure == 'validation' and candidate.exists():
                raise RuntimeError('isolated syntax failure')
            if self.failure == 'admin-stop':
                self.running = None
            elif self.failure == 'admin-change':
                self.running = {'pid': 99, 'birth': '999:1234'}
        return b''

    def clock(self):
        self.tick += 0.1
        return self.tick

    def process(self, pid):
        if self.running and self.running['pid'] == pid:
            return {**self.running, 'executable': apply.UNBOUND, 'uid': os.getuid(), 'stopped': False,
                    'argv': [apply.UNBOUND, '-d', '-c', str(self.root / 'unbound.conf')]}
        return None

    def kill(self, pid, signum):
        self.events.append(['signal', pid, signum])
        if self.failure == 'restart-alive':
            raise OSError('isolated signal failure before stop')
        self.assertEqual(pid, self.running['pid'])
        self.running = None

    def launch(self, command, **kwargs):
        self.events.append(command)
        self.launches += 1
        pid = 10 + self.launches
        failed = self.failure == 'recover' or (self.failure == 'restart' and self.launches == 1)
        if failed:
            self.running = None
        else:
            self.running = {'pid': pid, 'birth': '%d:1234' % (200 + self.launches)}
        return SimpleNamespace(pid=pid, poll=lambda: 1 if failed else (None if self.running and self.running['pid'] == pid else 0), wait=lambda timeout: 0)

    def attempt(self, failure='', remove=False):
        self.failure = failure
        try:
            return apply.transaction(remove=remove)
        except apply.ApplyError as error:
            return {'status': 'failed', 'code': error.code, 'detail': str(error)}

    def restarts(self):
        return sum(event[:1] == ['signal'] for event in self.events)

    def assert_restored(self):
        self.assertEqual(self.fragment.read_bytes(), self.old)
        self.assertEqual(self.runtime.read_bytes(), self.old)
        self.assertEqual(self.fragment.stat().st_mode & 0o777, 0o600)
        self.assertEqual(self.runtime.stat().st_mode & 0o777, 0o640)

    def test_valid_change_restarts_once_and_repeated_apply_keeps_same_process(self):
        self.assertEqual(self.attempt()['status'], 'ok')
        self.assertEqual(self.restarts(), 1)
        process = self.running.copy()
        self.assertFalse(self.attempt()['restarted'])
        self.assertEqual(self.running, process)
        self.assertEqual(self.restarts(), 1)
        self.assertEqual((self.state / 'applied.json').stat().st_mode & 0o777, 0o600)

    def test_template_and_candidate_trees_stay_below_private_state(self):
        self.assertEqual(self.attempt()['status'], 'ok')
        template_root = next(Path(command[2]) for command in self.events
                             if command[:2] == [apply.TEMPLATE_CTL, '-r'])
        candidate_main = next(Path(command[1]) for command in self.events
                              if command[0] == apply.CHECKCONF and Path(command[1]).is_absolute())
        self.assertEqual(template_root.parent, self.state)
        self.assertEqual(candidate_main.parent.parent, self.state)
        self.assertEqual(list(self.state.glob('.template-*')), [])
        self.assertEqual(list(self.state.glob('.check-*')), [])

