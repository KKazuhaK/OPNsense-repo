    def test_failure_after_owned_process_started_stops_only_our_child_and_restores_config(self):
        original = apply.atomic
        failed = [False]
        def write(path, *args, **kwargs):
            if path == self.state / 'applied.json' and not failed[0]:
                failed[0] = True
                raise OSError('isolated journal commit failure')
            return original(path, *args, **kwargs)
        with patch.object(apply, 'atomic', side_effect=write):
            self.assertEqual(self.attempt()['code'], 'apply_failed')
        self.assert_restored()
        self.assertEqual([event[1] for event in self.events if event[0] == 'signal'], [10, 11])
        self.assertEqual(self.running['pid'], 12)

