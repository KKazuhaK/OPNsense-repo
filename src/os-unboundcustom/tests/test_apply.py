    def test_corrupt_or_unsupported_receipts_preserve_all_files_before_any_command(self):
        valid = {'owned': {str(self.fragment): apply.snapshot(self.fragment), str(self.runtime): apply.snapshot(self.runtime)},
                 'closure': None, 'resolver': None}
        cases = ['{broken', '[]', 'null', '42', '"text"', '{}', json.dumps({**valid, 'owned': []}),
                 json.dumps({**valid, 'owned': {}}), json.dumps({**valid, 'resolver': {'pid': True, 'birth': '1:1'}}),
                 json.dumps({**valid, 'closure': 'bad'})]
        for bad in ({'data': '@bad', 'mode': 0o600, 'uid': 0, 'gid': 0},
                    {'data': '', 'mode': True, 'uid': 0, 'gid': 0}, []):
            cases.append(json.dumps({**valid, 'owned': {str(self.fragment): bad, str(self.runtime): None}}))
        for case in cases:
            for remove in [False, True]:
                with self.subTest(case=case, remove=remove):
                    (self.state / 'applied.json').write_text(case)
                    self.events.clear()
                    self.assertEqual(self.attempt(remove=remove)['code'], 'state_failed')
                    self.assert_restored()
                    self.assertEqual(self.events, [])
                    self.assertEqual(self.running['pid'], 10)

