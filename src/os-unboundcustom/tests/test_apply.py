    def test_recovery_rereads_pid_slot_after_original_exits_at_confirmation_boundary(self):
        original = {'pid': 10, 'birth': '100:1234'}
        slot = [original]
        launches = []
        attempt = {'stopped': False, 'term_sent': True}

        def confirm_exit():
            slot[0] = None
            return None

        def launch(restored):
            launches.append(restored)

        with (patch.object(apply, 'resolver', side_effect=confirm_exit),
              patch.object(apply, 'pidfile_identity', side_effect=lambda: slot[0]),
              patch.object(apply, 'process', return_value=None),
              patch.object(apply, 'validate', return_value=None),
              patch.object(apply, 'start_owned', side_effect=launch)):
            detail = apply.recover(original, attempt)
        self.assertTrue(attempt['stopped'])
        self.assertEqual(launches, [{'stopped': True}])
        self.assertIn('restored and started', detail)

